_COMMENTS_RE = re.compile(r"^##\s+Комментарии\s*$.*", re.S | re.M)
_FM_RE = re.compile(r"\A\+\+\+\n(.*?)\n\+\+\+\n?(.*)\Z", re.S)
_TITLE_RE = re.compile(r'^title\s*=\s*"(.*)"\s*$', re.M)
_TAGS_RE = re.compile(r"^tags\s*=\s*\[(.*?)\]\s*$", re.M)
_CATS_RE = re.compile(r"^categories\s*=\s*\[(.*?)\]\s*$", re.M)


def norm(text: str) -> str:
    text = _COMMENTS_RE.sub("", text)
    text = re.sub(r"https?://\S+", " ", text)
    return text.lower().replace("ё", "е")


CAT_COMPILED = {n: [(re.compile(p), w) for p, w in rs] for n, rs in CATEGORY_RULES.items()}
TAG_COMPILED = [(t, re.compile(p)) for t, p in TAG_RULES]


def classify(title: str, body: str):
    t, b = norm(title), norm(body)
    scores = {}
    for name, rules in CAT_COMPILED.items():
        s = 0
        for rx, w in rules:
            s += w * 3 * min(len(rx.findall(t)), 1)
            s += w * min(len(rx.findall(b)), 3)
        if s:
            scores[name] = s
    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    cats = []
    if ranked and ranked[0][1] >= 2:
        top = ranked[0][1]
        cats = [n for n, s in ranked if s >= 2 and s >= 0.5 * top][:MAX_CATEGORIES]
    if not cats:
        cats = [FALLBACK_CATEGORY]

    full = t + "\n" + b
    tags = [tag for tag, rx in TAG_COMPILED if rx.search(full)]
    return tags[:MAX_TAGS], cats


def toml_array(items):
    return "[" + ", ".join('"' + i.replace("\\", "\\\\").replace('"', '\\"') + '"' for i in items) + "]"


def process(path: Path, args, tag_counter, cat_counter) -> str:
    raw = path.read_text(encoding="utf-8")
    m = _FM_RE.match(raw)
    if not m:
        return "nofm"
    fm, body = m.groups()
    tm, cm = _TAGS_RE.search(fm), _CATS_RE.search(fm)
    if not tm or not cm:
        return "nofield"
    if not args.overwrite and (tm.group(1).strip() or cm.group(1).strip()):
        return "kept"
    ti = _TITLE_RE.search(fm)
    tags, cats = classify(ti.group(1) if ti else "", body)
    tag_counter.update(tags)
    cat_counter.update(cats)
    if args.dry_run:
        return "dry"
    new_fm = _TAGS_RE.sub(lambda _: "tags = " + toml_array(tags), fm, count=1)
    new_fm = _CATS_RE.sub(lambda _: "categories = " + toml_array(cats), new_fm, count=1)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(f"+++\n{new_fm}\n+++\n{body}", encoding="utf-8")
    tmp.replace(path)
    return "written"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(CONTENT_DIR))
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--overwrite", action="store_true")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    files = sorted(p for p in Path(args.dir).rglob("index.md") if not p.name.startswith("._"))
    if args.limit:
        files = files[: args.limit]
    res, tags, cats = collections.Counter(), collections.Counter(), collections.Counter()
    for p in files:
        try:
            res[process(p, args, tags, cats)] += 1
        except Exception as exc:  # keep the batch going
            res["error"] += 1
            print(f"ERROR {p}: {exc}", file=sys.stderr)
    print("results:", dict(res))
    print("categories:", cats.most_common())
    print("tags:", tags.most_common())


if __name__ == "__main__":
    main()
